    // Gestion du formulaire de contact avec AJAX
document.addEventListener('DOMContentLoaded', function() {
    const contactForm = document.querySelector('.php-email-form');
    
    if (contactForm) {
        contactForm.addEventListener('submit', async function(e) {
            e.preventDefault();
            
            const formData = new FormData(this);
            const submitButton = this.querySelector('button[type="submit"]');
            const originalButtonText = submitButton.innerHTML;
            
            // Désactiver le bouton et afficher le chargement
            submitButton.disabled = true;
            submitButton.innerHTML = '<i class="fas fa-spinner fa-spin"></i> Envoi en cours...';
            
            // Supprimer les messages précédents
            const existingMessages = this.querySelectorAll('.alert-message');
            existingMessages.forEach(msg => msg.remove());
            
            try {
                const response = await fetch('forms/test_local.php', {
                    method: 'POST',
                    body: formData
                });
                
                const result = await response.json();
                
                // Créer le message de réponse
                const messageDiv = document.createElement('div');
                messageDiv.className = `alert-message alert ${result.success ? 'alert-success' : 'alert-danger'}`;
                messageDiv.style.marginTop = '20px';
                messageDiv.style.padding = '15px';
                messageDiv.style.borderRadius = '8px';
                messageDiv.style.fontSize = '14px';
                messageDiv.style.textAlign = 'center';
                
                if (result.success) {
                    messageDiv.innerHTML = `
                        <i class="fas fa-check-circle"></i> 
                        <strong>Succès !</strong> ${result.message}
                    `;
                    messageDiv.style.backgroundColor = '#d4edda';
                    messageDiv.style.color = '#155724';
                    messageDiv.style.border = '1px solid #c3e6cb';
                    
                    // Réinitialiser le formulaire
                    contactForm.reset();
                    
                    // Animation de succès
                    messageDiv.style.animation = 'slideInDown 0.5s ease-out';
                    
                } else {
                    messageDiv.innerHTML = `
                        <i class="fas fa-exclamation-circle"></i> 
                        <strong>Erreur !</strong> ${result.message}
                    `;
                    messageDiv.style.backgroundColor = '#f8d7da';
                    messageDiv.style.color = '#721c24';
                    messageDiv.style.border = '1px solid #f5c6cb';
                }
                
                // Ajouter le message au formulaire
                contactForm.appendChild(messageDiv);
                
                // Faire défiler jusqu'au message
                messageDiv.scrollIntoView({ behavior: 'smooth', block: 'center' });
                
                // Supprimer le message après 8 secondes
                setTimeout(() => {
                    messageDiv.style.animation = 'slideOutUp 0.5s ease-out';
                    setTimeout(() => messageDiv.remove(), 500);
                }, 8000);
                
            } catch (error) {
                console.error('Erreur:', error);
                
                const errorDiv = document.createElement('div');
                errorDiv.className = 'alert-message alert alert-danger';
                errorDiv.style.marginTop = '20px';
                errorDiv.style.padding = '15px';
                errorDiv.style.borderRadius = '8px';
                errorDiv.style.backgroundColor = '#f8d7da';
                errorDiv.style.color = '#721c24';
                errorDiv.style.border = '1px solid #f5c6cb';
                errorDiv.style.textAlign = 'center';
                errorDiv.innerHTML = `
                    <i class="fas fa-times-circle"></i> 
                    <strong>Erreur réseau !</strong> 
                    Impossible de se connecter au serveur. Veuillez vérifier votre connexion et réessayer.
                `;
                
                contactForm.appendChild(errorDiv);
                
                setTimeout(() => {
                    errorDiv.style.animation = 'slideOutUp 0.5s ease-out';
                    setTimeout(() => errorDiv.remove(), 500);
                }, 8000);
            } finally {
                // Réactiver le bouton
                submitButton.disabled = false;
                submitButton.innerHTML = originalButtonText;
            }
        });
    }
