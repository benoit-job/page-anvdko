  <script>
    document.addEventListener("DOMContentLoaded", function () {
      let counters = document.querySelectorAll('.counter');
      let speed = 50; // Vitesse d'incrémentation

      const animateCounters = () => {
        counters.forEach(counter => {
          let updateCount = () => {
            let target = +counter.getAttribute('data-target');
            let count = +counter.innerText;
            let increment = target / speed;

            if (count < target) {
              counter.innerText = Math.ceil(count + increment);
              setTimeout(updateCount, 50);
            } else {
              counter.innerText = target;
            }
          };
          updateCount();
        });
      };

      // Déclencher l'animation quand la section est visible
      let sectionStats = document.querySelector("#stats");
      let options = { threshold: 0.5 }; // Lancer à 50% de visibilité

      let observer = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
          if (entry.isIntersecting) {
            animateCounters();
            observer.unobserve(sectionStats);
          }
        });
      }, options);

      observer.observe(sectionStats);
    });
  </script>
